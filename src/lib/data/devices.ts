export interface SwitchFilter {
  tech?: SwitchTech;
  minVdsV?: number;
  minIdA?: number;
  maxRdsOnMohm?: number;
}

/** Filter the switch database; every provided constraint must hold. */
export function findSwitches(f: SwitchFilter): SwitchDevice[] {
  return SWITCH_DEVICES.filter(
    (d) =>
      (f.tech === undefined || d.tech === f.tech) &&
      (f.minVdsV === undefined || d.vdsMaxV >= f.minVdsV) &&
      (f.minIdA === undefined || d.idMaxA >= f.minIdA) &&
      (f.maxRdsOnMohm === undefined || d.rdsOnMohm25 <= f.maxRdsOnMohm),
  );
}

/** Look up a switch by exact manufacturer part number. */
export function getSwitch(id: string): SwitchDevice | undefined {
  return SWITCH_DEVICES.find((d) => d.id === id);
}
